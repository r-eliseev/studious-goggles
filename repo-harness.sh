# Как устроен харнес

В репозитории установлен файловый харнес (repo harness): документация и задачи лежат в обычных markdown-файлах в git, правила для агентов записаны в `AGENTS.md`, а проверки выполняют скрипты. Привязки к конкретному агенту нет: подойдёт любой, который читает файлы и запускает команды. Установлен скриптом `repo-harness.sh`; его повторный запуск существующие файлы не перезаписывает (перезапись только с `--force`).

## Идея
- Агент читает документацию перед работой и обновляет её после.
- Правила, которые можно проверить автоматически, проверяются скриптом (`scripts/check.sh`, он же запускается в CI). Остальные правила пишутся коротко и в одном месте.
- Каждая повторяющаяся ошибка агента превращается в правило или проверку.

## Структура

```
AGENTS.md            точка входа для всех агентов
CLAUDE.md            одна строка: @AGENTS.md
docs/                документация (index.md — оглавление)
  decisions/         ADR: почему приняли то или иное решение
  specs/             спецификации фич
  log/               записи по сессиям
tasks/               задачи: <релиз|backlog>/NNN-имя.md
scripts/             скрипты задач и проверок
```

Документы делятся по скорости изменений: стабильные (product, architecture, conventions, decisions) меняются редко и осознанно; рабочие (specs, status, задачи) меняются по ходу работы; журнал (log) — новый файл на каждую запись, чтобы никто не конфликтовал в git.

## Задачи
Одна задача — один файл `tasks/<релиз|backlog>/NNN-имя.md`: описание, критерии готовности, анализ, план, отчёт, комментарии. Путь задачи: `todo` → `planned` (агент написал план) → `approved` (человек одобрил) → `in-progress` → `done`. Ещё есть `blocked` и `cancelled`. До одобрения плана агент код не пишет.

Команды:
- `scripts/new-task.sh --publish <релиз|backlog> <имя>` создать задачу;
- `scripts/list-tasks.sh [--main] [статус] [релиз]` показать «доску» (колонки — статусы, карточки — файлы);
- `scripts/claim-task.sh <номер> <имя>` занять задачу;
- `scripts/release-task.sh <номер> [--publish]` снять занятость;
- `scripts/release-notes.sh <релиз>` черновик заметок о релизе из выполненных задач;
- `scripts/check.sh` проверить документацию и задачи;
- `scripts/audit.sh [дней-занятости] [дней-устаревания-доков]` показать сигналы устаревания (см. ниже).

Канбан-доска текстом: карточка — файл задачи, колонка — значение `status`, перемещение карточки — правка `status`, обзор — `scripts/list-tasks.sh <статус>`. Колонки, где нужен человек: `planned` (ревью плана) и `blocked` (ответ в комментариях).

## Параллельная работа нескольких агентов
Исполнитель задачи записан в поле `assignee`. Занятие и создание задач делаются сразу в `origin/main` одним маленьким коммитом: если два агента пишут одновременно, git пропускает первого, а второй получает отказ (код 2) или следующий номер. Каждый агент работает в своей ветке `task/NNN-имя` (на одной машине — в своём `git worktree`). Агенты должны иметь право пушить в `main`; если `main` защищён, держите задачи в отдельном репозитории с той же раскладкой.

## Борьба с энтропией (аудит)
Со временем документация расходится с кодом, а код отходит от архитектуры. Против этого два уровня:
- механический: `scripts/audit.sh` показывает ошибки проверок, давно занятые (возможно, зависшие) задачи, задачи, которые ждут человека, документы, не менявшиеся намного дольше кода, и ADR без решения. Он же раз в неделю запускается в CI по расписанию (`.github/workflows/harness-audit.yml`);
- смысловой: отдельный агент по правилам из `docs/audit.md` сверяет документацию с кодом и ищет нарушения архитектуры. Очевидное он правит, остальное оформляет задачами и вопросами в `docs/status.md`, итог записывает в журнал. Запускайте его раз в неделю или перед релизом: харнес сам агента по расписанию не запускает.

Всё, что в аудите находится повторно, превращайте в автоматическую проверку (например, правила слоёв в тест архитектуры).

## Вспомогательные агенты (субагенты)
Если у агента есть механизм делегирования (субагенты в Claude Code и аналоги в других инструментах), правила описаны в `docs/subagents.md`: когда делегировать, как ставить поручение, кто за что отвечает. Главная идея: вспомогательный агент читает много и возвращает короткий вывод, поэтому контекст основного агента не засоряется. Задачу занимает и отвечает за неё основной агент. Если механизма нет, агент работает сам: харнес от него не зависит.

## Как развивать харнес
1. Дайте агенту реальную задачу.
2. Посмотрите, где он ошибся или пропустил шаг.
3. Классифицируйте причину: не хватало информации, правило было непонятным или его нельзя было проверить.
4. Исправьте в харнесе: добавьте факт в документацию, уточните правило или добавьте проверку в `scripts/check-docs.sh`.
5. Повторите. Если правило нарушается дважды, превращайте его в автоматическую проверку. Если `AGENTS.md` разросся, переносите детали в `docs/`.

Часть правил компенсирует слабости нынешних моделей и со временем станет ненужной: периодически удаляйте то, без чего агенты уже справляются.

## Ограничения
- Скрипты проверяют наличие и согласованность, а не качество: плохой план или формальный отчёт они не поймают.
- Одобрение плана скрипт проверить не может: оно держится на правиле и ревью pull request.
- Агент, который не вызвал `claim-task.sh`, обойдёт замок. Если агент завершился, не сняв занятость, задачу освобождает человек: `scripts/release-task.sh <номер> --publish`.
- Предупреждение «код изменён, а документация нет» только предупреждает: не каждая правка кода требует правки документации.
- Скрипт `audit.sh` находит только механические признаки устаревания. Смысловой аудит делает агент по `docs/audit.md`, и запускать его нужно вам; CI выполняет только механическую часть.
- Вспомогательные агенты зависят от инструмента: правила в `docs/subagents.md` работают, только если инструмент умеет делегировать.
- Скрипты проверялись на Linux с bash и git.
