# Вспомогательные агенты (субагенты)

Правила на случай, когда агент может делегировать часть работы вспомогательным агентам (в Claude Code это субагенты, в других инструментах механизм может называться иначе). Если такого механизма нет, выполняй работу сам: харнес от него не зависит.

## Зачем
Вспомогательный агент работает в своём контексте и возвращает только вывод. Это защищает контекст основного агента (так называемый контекстный брандмауэр): чтение десятков файлов и длинные логи не засоряют основную работу.

## Когда делегировать
- Разведка: найти, где в коде что-то используется, разобраться в незнакомом модуле, прочитать много файлов.
- Независимая проверка: ревью собственного диффа, сверка документации с кодом (аудит), поиск нарушений правил.
- Независимые подзадачи, которые не пересекаются по файлам.

## Когда не делегировать
- Маленькая задача, которую быстрее сделать самому.
- Правки, тесно связанные друг с другом или с одним и тем же файлом.
- Решения, для которых нужно понимать всю задачу: план, архитектура, выбор подхода.

## Как ставить поручение
Вспомогательный агент не видит твоего разговора, поэтому в поручении укажи:
1. цель и зачем она нужна;
2. где искать (файлы, каталоги) и что прочитать из `docs/`;
3. ограничения (не менять файлы, не запускать долгие команды);
4. формат ответа: краткий вывод со ссылками на файлы и строки, без пересказа всего прочитанного.

## Правила
- Ответственность за задачу остаётся на основном агенте. Именно он занимает задачу (`scripts/claim-task.sh`), ведёт «План» и «Отчёт» и отвечает за результат.
