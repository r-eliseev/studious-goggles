# ---------------------------------------------------------------- команды
do_init() {
  mkdir -p "$DIR" || die "не удалось создать каталог $DIR"
  TARGET="$(cd "$DIR" && pwd)"
  [ -n "$NAME" ] || NAME="$(basename "$TARGET")"
  echo "Устанавливаю харнес в $TARGET"
  if ! git -C "$TARGET" rev-parse --git-dir >/dev/null 2>&1; then
    echo "  предупреждение: это не git-репозиторий; для скриптов занятия задач нужны git и remote origin"
  fi
  do_files
  echo
  echo "Готово: создано $CREATED, пропущено $SKIPPED."
  [ $SKIPPED -eq 0 ] || echo "Пропущенные файлы уже существовали и не тронуты (перезаписать: --force)."
  cat <<'EOF'

Что дальше:
  1. Заполните docs/product.md, docs/architecture.md, docs/conventions.md, а в AGENTS.md
     команды, главные правила кода и запреты (места помечены угловыми скобками <...>).
  2. Проверьте: scripts/check.sh
  3. Закоммитьте и запушьте в основную ветку (занятие задач работает через origin/main).
  4. Создайте первую задачу: scripts/new-task.sh --publish release-1 первая-задача
  5. Описание харнеса для людей: docs/harness.md
  6. Раз в неделю или перед релизом: scripts/audit.sh и смысловой аудит по docs/audit.md
EOF
}

do_list() { MODE="list"; do_files; }

do_selftest() {
  local self d rc=0
  self="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"
  d=$(mktemp -d) || exit 1
  "$self" init --dir "$d" --name selftest >/dev/null || rc=1
  ( cd "$d" && git init -q . && scripts/check.sh >/dev/null \
      && scripts/new-task.sh release-1 demo >/dev/null && scripts/check.sh >/dev/null \
      && scripts/audit.sh >/dev/null ) || rc=1
  rm -rf "$d"
  if [ $rc -eq 0 ]; then echo "selftest: OK"; else echo "selftest: ОШИБКА"; fi
  return $rc
}

case "$cmd" in
  init)     do_init ;;
  list)     do_list ;;
  selftest) do_selftest ;;
  version|--version) echo "repo-harness $VERSION" ;;
  help|-h|--help) usage ;;
  *) die "неизвестная команда: $cmd (справка: ./repo-harness.sh help)" ;;
esac
