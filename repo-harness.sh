# Работа с задачами

Правила для агентов. Описание харнеса для людей: `docs/harness.md`.

Задачи лежат в `tasks/<релиз|backlog>/NNN-имя.md`. Одна задача — один файл: описание, критерии готовности, анализ, план, отчёт, комментарии. Над репозиторием могут работать несколько агентов одновременно.

## Имя исполнителя
Твоё имя — переменная окружения `AGENT_NAME` или имя, которое назвал пользователь. Если имени нет, придумай уникальное, например `claude-4f2a`. Имена разных агентов не должны совпадать.

## Начало работы
1. Прочитай файл задачи целиком, включая «Комментарии».
2. Посмотри, что делают другие: `scripts/list-tasks.sh --main in-progress`. Если в «Плане» чужой задачи в строке `Файлы:` есть файлы, которые собираешься менять и ты, не начинай: напиши комментарий в свою задачу и сообщи пользователю.
3. Займи задачу: `scripts/claim-task.sh <номер> <твоё-имя>`. Код 2 значит, что задача занята другим: остановись и сообщи пользователю. Другую задачу сам не бери.
4. Работай в отдельной ветке от свежего origin/main: `git fetch && git switch -c task/NNN-имя origin/main`. Если ветка `task/NNN-имя` уже есть на origin, продолжай в ней. Если рядом работают другие агенты на этой машине, используй отдельный worktree: `git worktree add ../wt-NNN -b task/NNN-имя origin/main`.

## Что делать, смотря на статус
- `todo`: прочитай описание и критерии, изучи код и `docs/`. Заполни «Анализ» и «План» (в плане строка `Файлы: ...`), поставь `planned` и остановись. Код не пиши.
- `planned`: ждёт ревью человека. Ничего не делай. Если пользователь просит поправить план по комментариям, поправь «План» и ответь комментарием.
- `approved`: можно реализовывать. `claim-task.sh` сам поставит `in-progress`.
- `in-progress`: продолжай реализацию.

## Одобрение
