- По умолчанию вспомогательный агент только читает. Если ему поручено править файлы, у каждого свой набор файлов (или свой git worktree), чтобы правки не пересекались.
- Выводы вспомогательного агента проверяй выборочно: открой ключевые файлы, которые он назвал, прежде чем опираться на них.
- Вспомогательный агент следует `AGENTS.md` так же, как основной. Не строй цепочки из вложенных агентов и не запускай их без необходимости: каждый стоит времени и денег.
