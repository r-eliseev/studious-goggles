#
# Что это: документация и задачи лежат в обычных markdown-файлах в git, правила для агентов
# в AGENTS.md, а правила, которые можно проверить автоматически, проверяют скрипты и CI.
# Харнес не привязан к конкретному агенту: подходит любой, который читает файлы и запускает команды.
# Идеи: Docs as Code + Tasks as Code, AGENTS.md как точка входа, spec-driven подход.
#
# В этом файле лежит всё, что нужно: AGENTS.md, шаблоны документов (с примерами), правила для агентов,
# шаблон задачи, скрипты (задачи, проверки, аудит), конфигурация CI, правила аудита документации
# (борьба с энтропией), правила для вспомогательных агентов (субагентов) и описание харнеса для людей.
#
# Использование:
#   ./repo-harness.sh init [параметры]   установить харнес в каталог (по умолчанию в текущий)
#   ./repo-harness.sh list               показать, какие файлы будут созданы
#   ./repo-harness.sh selftest           проверить установщик во временном каталоге
#   ./repo-harness.sh help               эта справка
#
# Параметры init:
#   --dir КАТАЛОГ    куда устанавливать (по умолчанию .)
#   --name ИМЯ       название проекта (по умолчанию имя каталога)
#   --desc ТЕКСТ     описание проекта для AGENTS.md
#   --build КОМАНДА  команда сборки
#   --test КОМАНДА   команда тестов
#   --lint КОМАНДА   команда линтера
#   --src КАТАЛОГ    каталог с кодом для предупреждения «код изменён, а документация нет» (по умолчанию src)
#   --no-ci          не создавать .github/workflows/harness.yml
#   --force          перезаписать уже существующие файлы (без него существующие файлы не трогаются)

set -u
shopt -u patsub_replacement 2>/dev/null || true

VERSION="1.0"

usage() { sed -n '2,/^$/!d;/^set -u/q;p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//' | sed '$d'; }
die() { echo "Ошибка: $*" >&2; exit 1; }

# ---------------------------------------------------------------- параметры
cmd="${1:-help}"; [ $# -gt 0 ] && shift
DIR="."; NAME=""; DESC="<одно-два предложения: что это за проект>"
BUILD="<команда сборки>"; TEST="<команда тестов>"; LINT="<команда линтера>"
SRC="src"; CI=1; FORCE=0
while [ $# -gt 0 ]; do
  case "$1" in
    --dir|--name|--desc|--build|--test|--lint|--src)
      [ $# -ge 2 ] || die "для $1 нужно значение"
      case "$1" in
        --dir) DIR="$2" ;; --name) NAME="$2" ;; --desc) DESC="$2" ;; --build) BUILD="$2" ;;
        --test) TEST="$2" ;; --lint) LINT="$2" ;; --src) SRC="$2" ;;
      esac
      shift 2 ;;
    --no-ci) CI=0; shift ;;
    --force) FORCE=1; shift ;;
    *) die "неизвестный параметр: $1 (справка: ./repo-harness.sh help)" ;;
  esac
done

MODE="install"; CREATED=0; SKIPPED=0; TARGET="."

# subst: печатает stdin с подстановкой параметров проекта
subst() {
  local s; s=$(cat; echo x); s=${s%x}
  s=${s//@@NAME@@/$NAME}; s=${s//@@DESC@@/$DESC}
  s=${s//@@BUILD@@/$BUILD}; s=${s//@@TEST@@/$TEST}; s=${s//@@LINT@@/$LINT}
  s=${s//@@SRC@@/$SRC}; s=${s//@@DATE@@/$(date +%F)}
  printf '%s' "$s"
}

# put <путь> [режим]: записывает файл (содержимое со stdin), существующие не трогает без --force
put() {
  local rel="$1" mode="${2:-644}" dest="$TARGET/$1"
  if [ "$MODE" = "list" ]; then echo "$rel"; cat >/dev/null; return; fi
  if [ -e "$dest" ] && [ $FORCE -eq 0 ]; then
    echo "  пропущен (уже есть): $rel"; cat >/dev/null; SKIPPED=$((SKIPPED + 1)); return
  fi
  mkdir -p "$(dirname "$dest")"
  subst > "$dest"; chmod "$mode" "$dest"
  echo "  создан: $rel"; CREATED=$((CREATED + 1))
}

